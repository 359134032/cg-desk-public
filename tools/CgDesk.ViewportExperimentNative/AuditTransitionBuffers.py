"""Generate exact instruction guards from the hash-bound, offline .text capture."""
import hashlib
import json
import re
import struct
from pathlib import Path
from AuditMapCache import RESEARCH, CAPTURE, instructions

code = (CAPTURE / 'code-section-00-text.bin').read_bytes()
assert hashlib.sha256(code).hexdigest() == '1e7f13e748c792586c7db2eb21d26d19f710bafecea02df6c2d6e44ad136d427'
listing = instructions(RESEARCH / 'map-audit-disassembly.txt')
bases = [0x10c9868, 0x10ca868, 0x10cb868]
records = []
for index, ins in enumerate(listing[:-1]):
    address = ins['address']
    if not 0x5588f0 <= address < 0x55a194:
        continue
    literals = [int(v, 16) for v in re.findall(r'\b([0-9A-F]+)h\b', ins['text'])]
    matches = [(v, n, v-base) for v in literals for n, base in enumerate(bases) if -8 <= v-base <= 0x30]
    if not matches:
        continue
    assert len(matches) == 1
    value, array, offset = matches[0]
    length = listing[index+1]['address'] - address
    assert 4 <= length <= 15
    raw = code[address-0x401000:address-0x401000+length]
    operand = raw.find(struct.pack('<I', value))
    assert operand >= 0 and raw.find(struct.pack('<I', value), operand+1) < 0
    records.append(dict(address=address, operand=address+operand, array=array, offset=offset,
                        length=length, bytes=raw.hex(), disassembly=ins['text']))
assert len(records) == 140
# Examine every byte-aligned literal in .text as a separate completeness check.
# A standalone 10C9860 scalar in 558210 is deliberately excluded. All array
# operand forms, including vector lanes, negative and +4 offsets, must be known.
known = {r['operand'] for r in records}
unresolved = []
for off in range(len(code)-3):
    value = struct.unpack_from('<I', code, off)[0]
    if any(-8 <= value-base <= 0x30 for base in bases):
        if off+0x401000 not in known and off+0x401000 != 0x55823c:
            unresolved.append((hex(off+0x401000), hex(value)))
assert not unresolved, unresolved
lines = ['// Generated by AuditTransitionBuffers.py from the hash-bound .text.', '#pragma once',
         'struct TransitionPatchSpec { uintptr_t address, operand; unsigned array; int offset; unsigned count; BYTE bytes[15]; };',
         'static const TransitionPatchSpec TransitionPatchSpecs[] = {']
for r in records:
    raw = ','.join('0x'+r['bytes'][i:i+2] for i in range(0, len(r['bytes']), 2))
    lines.append('    {0x%x,0x%x,%d,%d,%d,{%s}},' % (r['address'], r['operand'], r['array'], r['offset'], r['length'], raw))
lines.append('};')
Path(__file__).with_name('TransitionBufferProfile.h').write_text('\n'.join(lines)+'\n', encoding='ascii')
(RESEARCH / 'transition-buffer-operands.json').write_text(json.dumps(records, indent=2), encoding='utf-8')
print('Verified 140 complete transition-array instructions; no unresolved .text literals.')
